"""Gently process footer renders and write hashed JPGs + src/lib/footer-art-manifest.ts.

Usage: python scripts/footer-art.py <scene>=<png> [...]
Paper goes to white without clipping midtones (no autocontrast)."""
import hashlib, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public/engraving/footer"
MAN = ROOT / "src/lib/footer-art-manifest.ts"

entries = dict(re.findall(r'^\s+(\w+): "([^"]+)",$', MAN.read_text(), re.M))
for arg in sys.argv[1:]:
    scene, png = arg.split("=", 1)
    im = Image.open(png).convert("L").point(lambda v: 255 if v >= 242 else int(v * 255 / 242))
    tmp = OUT / f"{scene}.tmp.jpg"
    im.save(tmp, "JPEG", quality=85, optimize=True, progressive=True)
    h = hashlib.md5(tmp.read_bytes()).hexdigest()[:8]
    for old in OUT.glob(f"{scene}.*.jpg"):
        if old != tmp:
            old.unlink()
    final = OUT / f"{scene}.{h}.jpg"
    tmp.rename(final)
    entries[scene] = f"/engraving/footer/{final.name}"
    print(scene, final.name, final.stat().st_size // 1024, "KB")

body = "".join(f'  {k}: "{v}",\n' for k, v in sorted(entries.items()))
MAN.write_text(
    "// Generated by scripts/footer-art.py. Scene name -> hashed footer art path.\n"
    'import type { SceneName } from "@/lib/scenes";\n\n'
    "export const FOOTER_ART: Partial<Record<SceneName, string>> = {\n" + body + "};\n"
)
