"""Write hashed footer JPGs + src/lib/footer-art-manifest.ts from whitened renders.

Usage: python scripts/footer-art.py <scene>=<png> [...]
Inputs are 2x Real-ESRGAN upscales (3072 wide), already greyscale black
ink on warm paper (~250,250,248), so the grain is kept: no clipping. Scenes must be listed in src/lib/footer-scenes.ts;
manifest entries and JPGs for scenes no longer listed are removed."""
import hashlib, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public/engraving/footer"
MAN = ROOT / "src/lib/footer-art-manifest.ts"
VALID = set(re.findall(r'^\s+"(\w+)",$', (ROOT / "src/lib/footer-scenes.ts").read_text(), re.M))

entries = {k: v for k, v in re.findall(r'^\s+(\w+): "([^"]+)",$', MAN.read_text(), re.M) if k in VALID}
for arg in sys.argv[1:]:
    scene, png = arg.split("=", 1)
    if scene not in VALID:
        sys.exit(f"unknown scene {scene}: add it to src/lib/footer-scenes.ts")
    im = Image.open(png).convert("RGB")
    if im.width > 3072:
        im = im.resize((3072, round(im.height * 3072 / im.width)), Image.LANCZOS)
    tmp = OUT / f"{scene}.tmp.jpg"
    im.save(tmp, "JPEG", quality=82, optimize=True, progressive=True)
    h = hashlib.md5(tmp.read_bytes()).hexdigest()[:8]
    final = OUT / f"{scene}.{h}.jpg"
    tmp.rename(final)
    entries[scene] = f"/engraving/footer/{final.name}"
    print(scene, final.name, final.stat().st_size // 1024, "KB")

keep = {Path(v).name for v in entries.values()}
for old in OUT.glob("*.jpg"):
    if old.name not in keep:
        old.unlink()
        print("removed", old.name)

body = "".join(f'  {k}: "{v}",\n' for k, v in sorted(entries.items()))
MAN.write_text(
    "// Generated by scripts/footer-art.py. Footer scene -> hashed footer art path.\n"
    'import type { FooterScene } from "@/lib/footer-scenes";\n\n'
    "export const FOOTER_ART: Partial<Record<FooterScene, string>> = {\n" + body + "};\n"
)
