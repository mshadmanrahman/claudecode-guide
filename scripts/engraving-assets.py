#!/usr/bin/env python3
"""Turn Codex engraving renders into the site's ink-on-white panel assets.

Reads public/_compare/eng-band-<scene>.png (the git-excluded render folder),
plus eng-icon-<name>.png for the small card icons (public/engraving/icons/),
writes public/engraving/<scene>.<hash>.jpg as grey ink on pure white, and regenerates
src/lib/engraving-manifest.ts so components only reference scenes that exist.
The content hash in the filename means a re-render always gets a new URL, so
no browser or image cache can keep showing the old picture.

The renders come back with a cream or sepia cast. Greyscale plus a levels
stretch pushes the paper to #fff, which is what lets the panels multiply
cleanly onto the light theme. Dark mode shows them as prints on paper.

Usage: python3 scripts/engraving-assets.py [extra.png=scene ...]
"""

import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "_compare"
OUT = ROOT / "public" / "engraving"
MANIFEST = ROOT / "src" / "lib" / "engraving-manifest.ts"
WIDTH = 1536
ICON_WIDTH = 256


def save(img: Image.Image, folder: Path, name: str, quality: int) -> None:
    """Write <name>.<hash>.jpg and drop any older file for the same name."""
    tmp = folder / f"{name}.tmp.jpg"
    img.save(tmp, quality=quality, optimize=True, progressive=True)
    digest = hashlib.sha1(tmp.read_bytes()).hexdigest()[:8]
    for old in [*folder.glob(f"{name}.jpg"), *folder.glob(f"{name}.????????.jpg")]:
        old.unlink()
    tmp.rename(folder / f"{name}.{digest}.jpg")


def files(folder: Path) -> dict[str, str]:
    return {p.name.split(".")[0]: p.name for p in sorted(folder.glob("*.*.jpg"))}


def convert_icon(src: Path, name: str) -> None:
    img = ImageOps.autocontrast(ImageOps.grayscale(Image.open(src)), cutoff=(1, 6))
    img = img.resize((ICON_WIDTH, round(img.height * ICON_WIDTH / img.width)), Image.Resampling.LANCZOS)
    save(img, OUT / "icons", name, 85)


def convert(src: Path, scene: str, folder: Path = OUT) -> None:
    img = ImageOps.grayscale(Image.open(src))
    # Paper to white, ink kept: clip the brightest 6% and darkest 1%.
    img = ImageOps.autocontrast(img, cutoff=(1, 6))
    if img.width > WIDTH:
        img = img.resize((WIDTH, round(img.height * WIDTH / img.width)), Image.Resampling.LANCZOS)
    save(img, folder, scene, 80)


def main() -> None:
    (OUT / "band").mkdir(parents=True, exist_ok=True)
    for src in sorted(SRC.glob("eng-band-*.png")):
        if src.stem.endswith("-rejected"):
            continue
        if src.stem.endswith("-landscape"):  # the footer band keeps the landscape
            convert(src, src.stem.removeprefix("eng-band-").removesuffix("-landscape"), OUT / "band")
            continue
        convert(src, src.stem.removeprefix("eng-band-"))
    (OUT / "icons").mkdir(exist_ok=True)
    for src in sorted(SRC.glob("eng-icon-*.png")):
        convert_icon(src, src.stem.removeprefix("eng-icon-"))
    for pair in sys.argv[1:]:
        path, scene = pair.split("=")
        convert(Path(path), scene)

    scenes = files(OUT)
    lines = "".join(f'  ["{k}", "{v}"],\n' for k, v in scenes.items())
    icons = files(OUT / "icons")
    bands = files(OUT / "band")
    band_lines = "".join(f'  ["{k}", "{v}"],\n' for k, v in bands.items())
    icon_lines = "".join(f'  ["{k}", "{v}"],\n' for k, v in icons.items())
    MANIFEST.write_text(
        "// Generated by scripts/engraving-assets.py. Do not edit by hand.\n"
        'import type { SceneName } from "@/lib/scenes";\n\n'
        "/** Scenes with an engraving, mapped to their hashed file in public/engraving/. */\n"
        f"export const ENGRAVED: ReadonlyMap<SceneName, string> = new Map<SceneName, string>([\n{lines}]);\n\n"
        "/** Card icons, mapped to their hashed file in public/engraving/icons/. */\n"
        f"export const ICONS: ReadonlyMap<string, string> = new Map<string, string>([\n{icon_lines}]);\n\n"
        "/** Footer-band landscapes for scenes whose panel now shows a person, in public/engraving/band/. */\n"
        f"export const BANDS: ReadonlyMap<SceneName, string> = new Map<SceneName, string>([\n{band_lines}]);\n"
    )
    print(f"{len(scenes)} engravings, {len(icons)} icons")


if __name__ == "__main__":
    main()
